#!/usr/bin/env python3
"""Builds the red colours for the Perps' Crime Board at the end of crimeboard.css.

The Perps' board is the Judges' Crime Board with every blue/cyan turned dark red. This reads every rule in
crimeboard.css (above the generated section), keeps only the declarations that contain a blue or
cyan colour (or the night-city background picture), and writes them again under "#cb.market" with
the colours converted. Team colours (--gold/--red/--green/--gm and the GM chips) are left alone.
Run it again after changing crimeboard.css:   python make_market_css.py path/to/crimeboard.css
The colour maths matches tintRgb() in crimeboard.js.
"""
import re, sys

MARK = '/* ===== PERPS\' CRIME BOARD - RED (generated by tools/make_market_css.py - do not edit by hand) ===== */'

def tint_rgb(r, g, b):
    r, g, b = r / 255, g / 255, b / 255
    mx, mn = max(r, g, b), min(r, g, b)
    l = (mx + mn) / 2; d = mx - mn
    if d < 0.0001: return None
    sat = d / (1 - abs(2 * l - 1))
    if mx == r: h = ((g - b) / d) % 6
    elif mx == g: h = (b - r) / d + 2
    else: h = (r - g) / d + 4
    h = (h * 60 + 360) % 360
    if h < 165 or h > 265 or sat < 0.12: return None
    S = min(1, sat * 0.9); L = l if l > 0.8 else l * 0.72; H = 352
    c = (1 - abs(2 * L - 1)) * S; x = c * (1 - abs((H / 60) % 2 - 1)); m = L - c / 2
    return [round((v + m) * 255) for v in (c, 0, x)]

def retint(text):
    def hx(mo):
        hexs = mo.group(1)
        if len(hexs) == 3: hexs = ''.join(ch * 2 for ch in hexs)
        t = tint_rgb(int(hexs[0:2], 16), int(hexs[2:4], 16), int(hexs[4:6], 16))
        return '#' + ''.join('%02x' % v for v in t) if t else mo.group(0)
    def rg(mo):
        t = tint_rgb(int(mo.group(1)), int(mo.group(2)), int(mo.group(3)))
        if not t: return mo.group(0)
        a = mo.group(4) or ''
        return ('rgba(' if a else 'rgb(') + ', '.join(map(str, t)) + a + ')'
    out = re.sub(r'#([0-9a-fA-F]{6}|[0-9a-fA-F]{3})\b', hx, text)
    out = re.sub(r'rgba?\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*(,\s*[\d.]+\s*)?\)', rg, out)
    return out.replace('cb-bg.webp', 'cb-bg-market.webp')

def blocks(text):
    out, i, n = [], 0, len(text)
    while i < n:
        j = text.find('{', i)
        if j < 0: break
        pre = text[i:j].strip(); depth, k = 1, j + 1
        while depth:
            if text[k] == '{': depth += 1
            elif text[k] == '}': depth -= 1
            k += 1
        out.append((pre, text[j + 1:k - 1])); i = k
    return out

def decls(body):
    # split on ; that aren't inside brackets or quotes
    parts, depth, cur, q = [], 0, '', None
    for ch in body:
        if q:
            cur += ch
            if ch == q: q = None
            continue
        if ch in '"\'': q = ch
        elif ch == '(': depth += 1
        elif ch == ')': depth -= 1
        if ch == ';' and depth == 0: parts.append(cur); cur = ''
        else: cur += ch
    if cur.strip(): parts.append(cur)
    return [p.strip() for p in parts if ':' in p]

KEEP = {'--gold', '--red', '--green', '--gm'}
renamed = {}

def market_sel(sel):
    sel = sel.strip()
    if 'GM' in sel: return None
    if sel.startswith('#cb'): return '#cb.market' + sel[3:]
    if sel.startswith('#crimeboard-open-button'): return None
    return None

def emit(bl):
    out = []
    for pre, body in bl:
        if pre.startswith('@font-face'): continue
        if pre.startswith('@keyframes'):
            name = pre.split()[1]
            new = retint(body)
            if new != body:
                renamed[name] = name + 'Market'
                out.append('@keyframes %sMarket {%s}' % (name, new))
            continue
        if pre.startswith('@media') or pre.startswith('@supports'):
            inner = emit(blocks(body))
            if inner.strip(): out.append(pre + ' {\n' + inner + '\n}')
            continue
        sels = [market_sel(x) for x in pre.split(',')]
        sels = [x for x in sels if x]
        if not sels: continue
        keep = []
        for d in decls(body):
            prop, val = d.split(':', 1)
            prop = prop.strip()
            if prop in KEEP: continue
            new = retint(val)
            if prop in ('animation', 'animation-name'):
                for a, b in renamed.items(): new = re.sub(r'\b%s\b' % a, b, new)
            if new != val: keep.append('%s:%s' % (prop, new))
        if keep: out.append(', '.join(sels) + ' {' + '; '.join(keep) + ';}')
    return '\n'.join(out)

path = sys.argv[1] if len(sys.argv) > 1 else 'crimeboard.css'
css = open(path, encoding='utf-8').read()
base = css.split('\n' + MARK)[0].rstrip('\n')
clean = re.sub(r'/\*.*?\*/', '', base, flags=re.S)
# keyframes first, so rules that use a recoloured animation can point at the red copy
for pre, body in blocks(clean):
    if pre.startswith('@keyframes') and retint(body) != body: renamed[pre.split()[1]] = pre.split()[1] + 'Market'
gen = emit(blocks(clean))
extra = """
/* the Perps' Crime Board button under the panel */
#blockmarket-open-button { background: #3a0710; color: #ffd21f; border-color: #c4122b; letter-spacing: 2px; }
#blockmarket-open-button:hover { background: #5c0b18; }
/* terminal prompts: the street, not M.A.C. */
#cb.market .popout-hint::before, #cb.market .toast::before, #cb.market .gate-card p::before, #cb.market .obs-caption::before { content: "STREET > "; }
#cb.market .status::before { content: "STREET >"; }
"""
open(path, 'w', encoding='utf-8').write(base + '\n\n' + MARK + '\n' + gen + '\n' + extra)
print('market rules:', gen.count('{'), 'renamed keyframes:', renamed)
